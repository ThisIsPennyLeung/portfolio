import { RootLayout as PageRootLayout } from "@/app/_components/page/RootLayout"
import { Background } from "@/app/_components/widget/background/background"
import { Center } from "@/app/_components/widget/center/center"
import { Expanded } from "@/app/_components/widget/expanded/expanded"
import { Padding } from "@/app/_components/widget/padding/padding"
import { joinCss } from "@/app/_lib/utils"
import { config as fontawesomeConfig } from "@fortawesome/fontawesome-svg-core"
import "@fortawesome/fontawesome-svg-core/styles.css"
import type { Metadata } from "next"
import { Geist, Geist_Mono } from "next/font/google"
import { ReactNode } from "react"
import "./globals.css"
import { ImageTeleportContext } from "./_components/widget/image/image"
import { TeleportContextProvider } from "./_components/widget/teleport/teleport"

fontawesomeConfig.autoAddCss = false

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
})

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
})

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
}

const Providers = ({
  children,
}: Readonly<{
  children: ReactNode
}>) => {
  return (
    <TeleportContextProvider
      context={ImageTeleportContext}
      closeOnBackdropClicked={true}
    >
      {children}
    </TeleportContextProvider>
  )
}

const RootLayout = ({
  children,
}: Readonly<{
  children: ReactNode
}>) => {
  return (
    <html lang="en" className={joinCss(geistSans.variable, geistMono.variable)}>
      <body>
        <Expanded>
          <Background>
            <Padding direction="immediateUnderRoot">
              <Providers>
                <Center axis="horizontal">
                  <PageRootLayout>{children}</PageRootLayout>
                </Center>
              </Providers>
            </Padding>
          </Background>
        </Expanded>
      </body>
    </html>
  )
}
export default RootLayout
